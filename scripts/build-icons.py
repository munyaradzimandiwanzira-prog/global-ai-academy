#!/usr/bin/env python3
"""
Builds the self-hosted Material Symbols Outlined subset used by <MaterialIcon>.

  1. Collects every symbol name the app uses: the ICONS map in src/components/icons.tsx plus any
     literal <MaterialIcon name="…"> in src/.
  2. Pins the variable font to the locked axes FILL 0 · wght 100 · GRAD 0 · opsz 24 (a static instance,
     exactly what Google Fonts serves for `@24,100,0,0`).
  3. Keeps only those glyphs (addressed by their private-use code points, so no ligature table ships)
     and writes public/fonts/material-symbols-outlined.woff2 and src/components/icon-codepoints.ts.

Fails loudly if a name doesn't exist in the font, so a wrong name can never reach the screen as text.
Run: npm run icons   (needs: pip install fonttools brotli)
"""
import json
import pathlib
import re
import sys

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'node_modules/@fontsource-variable/material-symbols-outlined/files/material-symbols-outlined-latin-full-normal.woff2'
OUT_FONT = ROOT / 'public/fonts/material-symbols-outlined.woff2'
OUT_TS = ROOT / 'src/components/icon-codepoints.ts'
AXES = {'FILL': 0, 'wght': 100, 'GRAD': 0, 'opsz': 24}


def ligature_codepoints(font: TTFont) -> dict:
    """symbol name -> private-use code point, read from the font's own ligature table."""
    cmap = font.getBestCmap()
    by_glyph = {}
    for cp, glyph in cmap.items():
        if cp >= 0xE000:
            by_glyph.setdefault(glyph, cp)
    chars = {glyph: chr(cp) for cp, glyph in cmap.items() if cp < 0x80}
    names = {}
    for lookup in font['GSUB'].table.LookupList.Lookup:
        for table in lookup.SubTable:
            if lookup.LookupType == 7:
                table = table.ExtSubTable
            for first, ligatures in getattr(table, 'ligatures', {}).items():
                for lig in ligatures:
                    parts = [first, *lig.Component]
                    if all(p in chars for p in parts) and lig.LigGlyph in by_glyph:
                        names[''.join(chars[p] for p in parts)] = by_glyph[lig.LigGlyph]
    return names


def used_names() -> set:
    names = set()
    icons_src = (ROOT / 'src/components/icons.tsx').read_text()
    block = re.search(r'export const ICONS = \{(.*?)\} as const', icons_src, re.S)
    names.update(re.findall(r":\s*'([a-z0-9_]+)'", block.group(1)))
    for path in (ROOT / 'src').rglob('*.tsx'):
        names.update(re.findall(r'<MaterialIcon[^>]*\bname="([a-z0-9_]+)"', path.read_text()))
        names.update(re.findall(r"\bsymbol:\s*'([a-z0-9_]+)'", path.read_text()))
    return names


def main() -> int:
    font = TTFont(SOURCE)
    table = ligature_codepoints(font)
    wanted = sorted(used_names())
    missing = [n for n in wanted if n not in table]
    if missing:
        print('Unknown Material Symbols:', ', '.join(missing), file=sys.stderr)
        return 1

    static = instancer.instantiateVariableFont(font, AXES)
    options = subset.Options()
    options.layout_features = []          # code points only: no ligature table to ship
    options.flavor = 'woff2'
    options.name_IDs = ['*']
    options.notdef_outline = True
    sub = subset.Subsetter(options)
    sub.populate(unicodes=[table[n] for n in wanted])
    sub.subset(static)
    OUT_FONT.parent.mkdir(parents=True, exist_ok=True)
    static.flavor = 'woff2'
    static.save(OUT_FONT)

    entries = '\n'.join(f"  {n}: 0x{table[n]:x}," for n in wanted)
    OUT_TS.write_text(
        '// Generated by scripts/build-icons.py — do not edit. Run `npm run icons` after adding a symbol.\n'
        '// Material Symbols Outlined, static instance FILL 0 · wght 100 · GRAD 0 · opsz 24.\n'
        f'export const CODEPOINTS = {{\n{entries}\n}} as const;\n\n'
        'export type SymbolName = keyof typeof CODEPOINTS;\n'
    )
    print(f'{len(wanted)} symbols -> {OUT_FONT.relative_to(ROOT)} ({OUT_FONT.stat().st_size / 1024:.1f} KB)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
